items = []
relations = []  # (parent_idx, child_idx)
idx_of = {}     # content -> idx（字/词按内容索引）

# L0
for i, (ch, py, meaning, tip, group) in enumerate(L0):
    items.append({
        "id": f"R{i+1:03d}", "type": "字根", "level": 0, "group": group,
        "content": ch, "pinyin": py, "meaning": meaning,
        "componentsNote": "象形独体字", "teachingTip": tip,
        "sortOrder": i + 1, "status": "启用",
    })
    idx_of[ch] = i

# L1
base = len(items)
for j, (ch, py, comp, tip, comps) in enumerate(L1):
    idx = len(items)
    items.append({
        "id": f"C{j+1:03d}", "type": "汉字", "level": 1,
        "content": ch, "pinyin": py, "meaning": None,
        "componentsNote": comp, "teachingTip": tip,
        "sortOrder": j + 1, "status": "启用",
    })
    idx_of[ch] = idx
    for c in comps:
        if c in idx_of:
            relations.append((idx, idx_of[c]))

# L2
for k, (word, py, comps, tip) in enumerate(L2):
    idx = len(items)
    items.append({
        "id": f"W{k+1:03d}", "type": "词语", "level": 2,
        "content": word, "pinyin": py, "meaning": None,
        "componentsNote": "+".join(comps), "teachingTip": tip,
        "sortOrder": k + 1, "status": "启用",
    })
    for c in comps:
        if c in idx_of:
            relations.append((idx, idx_of[c]))

# L3
